"""Generate db/02_seed.sql: 10 service areas, 50 fake customers, a few outages.

Run:  python scripts/generate_seed.py
Output is deterministic (fixed random seed), so the committed SQL only changes
when this script does. All names are invented; phone numbers use the 555
range so none belong to a real person.
"""
import random
from pathlib import Path

random.seed(42)

AREAS = [
    ("Port of Spain", "North"), ("Diego Martin", "North"), ("Arima", "East"),
    ("Tunapuna", "East"), ("Sangre Grande", "East"), ("Chaguanas", "Central"),
    ("Couva", "Central"), ("San Fernando", "South"), ("Point Fortin", "South"),
    ("Scarborough", "Tobago"),
]
FIRST = ["Aaliyah", "Marcus", "Priya", "Jason", "Keisha", "Ravi", "Natalie", "Andre",
         "Shanice", "Kevin", "Anjali", "Darren", "Tricia", "Rohan", "Melissa", "Kyle",
         "Sasha", "Imran", "Danielle", "Tyrone", "Kavita", "Shane", "Renee", "Vishal"]
LAST = ["Ramdial", "Charles", "Mohammed", "Joseph", "Baptiste", "Persad", "Williams",
        "Ali", "Phillip", "Maharaj", "George", "Thomas", "Singh", "Clarke", "Roberts",
        "Lewis", "Rampersad", "Pierre", "Ramsaran", "Alexander"]
SERVICES = ["fibre", "fibre", "dsl", "mobile", "fixed_wireless"]

# (area index, service, cause, started N minutes ago, ETA N minutes from now, status)
OUTAGES = [
    (0, "fibre", "Fibre cut during roadworks on Ariapita Ave", 95, 120, "active"),
    (5, "dsl", "Power failure at exchange", 40, 180, "active"),
    (7, "mobile", "Cell site hardware fault", 20, 60, "active"),
    (9, "fixed_wireless", "Storm damage to tower antenna", 300, 600, "active"),
    (2, "fibre", "Scheduled maintenance", 2880, None, "resolved"),
    (7, "fibre", "Splice failure at street cabinet", 1440, None, "resolved"),
]


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


lines = ["-- Generated by scripts/generate_seed.py. Do not edit by hand.", ""]

lines.append("INSERT INTO service_areas (name, region) VALUES")
lines.append(",\n".join(f"  ({q(n)}, {q(r)})" for n, r in AREAS) + ";\n")

used = set()
rows = []
for i in range(50):
    while True:
        name = f"{random.choice(FIRST)} {random.choice(LAST)}"
        if name not in used:
            used.add(name)
            break
    # The first 10 customers get one per area so every area has someone to test with.
    area_id = (i % 10) + 1 if i < 10 else random.randint(1, 10)
    service = random.choice(SERVICES)
    status = "suspended" if random.random() < 0.06 else "active"
    email = name.lower().replace(" ", ".") + "@example.com"
    rows.append(f"  ({q(f'ACC-{100001 + i}')}, {q(name)}, {q('+1868555' + str(1000 + i).zfill(4))}, "
                f"{q(email)}, {q(service)}, {area_id}, {q(status)})")
lines.append("INSERT INTO customers (account_no, full_name, phone, email, service_type, area_id, status) VALUES")
lines.append(",\n".join(rows) + ";\n")

rows = []
for area, svc, cause, ago, eta, status in OUTAGES:
    started = f"now() - interval '{ago} minutes'"
    if status == "active":
        eta_sql, resolved = f"now() + interval '{eta} minutes'", "NULL"
    else:
        eta_sql, resolved = "NULL", f"now() - interval '{ago - 180} minutes'"
    rows.append(f"  ({area + 1}, {q(svc)}, {q(cause)}, {q(status)}, {started}, {eta_sql}, {resolved})")
lines.append("INSERT INTO outages (area_id, service_type, cause, status, started_at, eta, resolved_at) VALUES")
lines.append(",\n".join(rows) + ";\n")

out = Path(__file__).resolve().parent.parent / "db" / "02_seed.sql"
out.write_text("\n".join(lines))
print(f"Wrote {out}")
